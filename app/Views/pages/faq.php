<div class="faq-list">
    <details>
        <summary>Que préparer pour un ourlet ?</summary>
        <p>Si possible, prévoyez le vêtement et les chaussures que vous porterez avec. Cela aide à évaluer la longueur en situation.</p>
    </details>
    <details>
        <summary>Peut-on ajuster tous les vêtements ?</summary>
        <p>La faisabilité dépend notamment de la coupe, de la matière et de la marge de tissu disponible. La pièce doit être examinée avant de confirmer la retouche.</p>
    </details>
    <details>
        <summary>Comment préparer un projet sur mesure ?</summary>
        <p>Notez l’usage de la pièce, les matières que vous aimez et la date souhaitée. Vous pouvez aussi réunir des images pour montrer le style recherché.</p>
    </details>
    <details>
        <summary>Comment le prix est-il déterminé ?</summary>
        <p>Il dépend de la prestation, des matières et de la complexité du travail. La page <a href="/index.php/tarifs">Tarifs</a> présente des exemples de démonstration.</p>
    </details>
    <details>
        <summary>Une intervention à domicile est-elle possible ?</summary>
        <p>Elle dépend de la prestation et de la commune. Le lieu d’intervention doit être précisé avant le rendez-vous.</p>
    </details>
</div>
